const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// 1) 화면용 HTML — JS 없이도 펼쳐지는 <details>
let html = '';
FAQ.forEach(([cat, q, a]) => {
  html += `    <details class="qa" data-cat="${cat}">
      <summary><span class="q">Q</span><span class="t">${esc(q)}</span></summary>
      <div class="a">${esc(a)}</div>
    </details>\n`;
});

// 2) FAQPage 구조화 데이터
const jsonld = {
  '@context': 'https://schema.org',
  '@type': 'FAQPage',
  mainEntity: FAQ.map(([, q, a]) => ({
    '@type': 'Question',
    name: q,
    acceptedAnswer: { '@type': 'Answer', text: a },
  })),
};

fs.writeFileSync(process.argv[2], html, 'utf8');
fs.writeFileSync(process.argv[3], JSON.stringify(jsonld, null, 2), 'utf8');
console.log('FAQ 항목:', FAQ.length, '| HTML', html.length, 'chars');
